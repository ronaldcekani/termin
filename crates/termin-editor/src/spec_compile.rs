//! Compilation of TOML command specs into static Rust tables.
//!
//! See `docs/specs/input-editor.md §4.2`.

use crate::spec::*;

/// Parse a TOML string into a CommandSpec.
pub fn parse_spec_toml(content: &str) -> Result<CommandSpec, toml::de::Error> {
    toml::from_str(content)
}

/// Codegen: convert a list of CommandSpecs into Rust source code defining `StaticCommandSpec`s.
pub fn compile_specs_to_rust(specs: &[CommandSpec]) -> String {
    let mut out = String::new();
    out.push_str("// Auto-generated by termin-editor spec compiler. DO NOT EDIT.\n");
    out.push_str("use crate::spec::*;\n\n");

    for (i, spec) in specs.iter().enumerate() {
        let var_name = format!("SPEC_{}_{}", i, sanitize_ident(&spec.name).to_uppercase());
        emit_command_spec(&mut out, &var_name, spec);
        out.push('\n');
    }

    out.push_str("pub static COMPILED_SPECS: &[StaticCommandSpec] = &[\n");
    for (i, spec) in specs.iter().enumerate() {
        let var_name = format!("SPEC_{}_{}", i, sanitize_ident(&spec.name).to_uppercase());
        out.push_str(&format!("    {},\n", var_name));
    }
    out.push_str("];\n\n");

    out.push_str(
        "pub fn find_compiled_spec(name_or_alias: &str) -> Option<&'static StaticCommandSpec> {\n",
    );
    out.push_str("    COMPILED_SPECS\n");
    out.push_str("        .iter()\n");
    out.push_str("        .find(|spec| spec.name == name_or_alias || spec.aliases.contains(&name_or_alias))\n");
    out.push_str("}\n");

    out
}

fn emit_command_spec(out: &mut String, ident: &str, spec: &CommandSpec) {
    out.push_str(&format!(
        "pub static {}: StaticCommandSpec = StaticCommandSpec {{\n",
        ident
    ));
    out.push_str(&format!("    name: {:?},\n", spec.name));
    out.push_str(&format!("    aliases: &{:?},\n", spec.aliases));
    out.push_str(&format!("    description: {:?},\n", spec.description));

    // Subcommands
    out.push_str("    subcommands: &[\n");
    for sub in &spec.subcommands {
        emit_subcommand_spec(out, sub, 2);
    }
    out.push_str("    ],\n");

    // Options
    out.push_str("    options: &[\n");
    for opt in &spec.options {
        emit_option_spec(out, opt, 2);
    }
    out.push_str("    ],\n");

    // Args
    out.push_str("    args: &[\n");
    for arg in &spec.args {
        emit_arg_spec(out, arg, 2);
    }
    out.push_str("    ],\n");

    // Persistent options
    out.push_str("    persistent_options: &[\n");
    for opt in &spec.persistent_options {
        emit_option_spec(out, opt, 2);
    }
    out.push_str("    ],\n");

    out.push_str("};\n");
}

fn emit_subcommand_spec(out: &mut String, sub: &SubcommandSpec, indent_level: usize) {
    let ind = "    ".repeat(indent_level);
    out.push_str(&format!("{}StaticSubcommandSpec {{\n", ind));
    out.push_str(&format!("{}    name: {:?},\n", ind, sub.name));
    out.push_str(&format!("{}    aliases: &{:?},\n", ind, sub.aliases));
    out.push_str(&format!("{}    description: {:?},\n", ind, sub.description));

    out.push_str(&format!("{}    subcommands: &[\n", ind));
    for s in &sub.subcommands {
        emit_subcommand_spec(out, s, indent_level + 2);
    }
    out.push_str(&format!("{}    ],\n", ind));

    out.push_str(&format!("{}    options: &[\n", ind));
    for opt in &sub.options {
        emit_option_spec(out, opt, indent_level + 2);
    }
    out.push_str(&format!("{}    ],\n", ind));

    out.push_str(&format!("{}    args: &[\n", ind));
    for arg in &sub.args {
        emit_arg_spec(out, arg, indent_level + 2);
    }
    out.push_str(&format!("{}    ],\n", ind));

    out.push_str(&format!("{}}},\n", ind));
}

fn emit_option_spec(out: &mut String, opt: &OptionSpec, indent_level: usize) {
    let ind = "    ".repeat(indent_level);
    out.push_str(&format!("{}StaticOptionSpec {{\n", ind));
    out.push_str(&format!("{}    names: &{:?},\n", ind, opt.names));
    out.push_str(&format!("{}    description: {:?},\n", ind, opt.description));
    out.push_str(&format!("{}    args: &[\n", ind));
    for arg in &opt.args {
        emit_arg_spec(out, arg, indent_level + 2);
    }
    out.push_str(&format!("{}    ],\n", ind));
    out.push_str(&format!("{}    repeatable: {:?},\n", ind, opt.repeatable));
    out.push_str(&format!("{}}},\n", ind));
}

fn emit_arg_spec(out: &mut String, arg: &ArgSpec, indent_level: usize) {
    let ind = "    ".repeat(indent_level);
    out.push_str(&format!("{}StaticArgSpec {{\n", ind));
    out.push_str(&format!("{}    name: {:?},\n", ind, arg.name));
    out.push_str(&format!("{}    optional: {:?},\n", ind, arg.optional));
    out.push_str(&format!("{}    variadic: {:?},\n", ind, arg.variadic));
    out.push_str(&format!(
        "{}    suggestions: &{:?},\n",
        ind, arg.suggestions
    ));
    out.push_str(&format!("{}    generators: &{:?},\n", ind, arg.generators));
    let t_str = match &arg.template {
        Some(t) => format!("Some({:?})", t),
        None => "None".to_string(),
    };
    out.push_str(&format!("{}    template: {},\n", ind, t_str));
    out.push_str(&format!("{}}},\n", ind));
}

fn sanitize_ident(name: &str) -> String {
    name.replace(['-', '.', ' ', '/'], "_")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parse_and_compile_spec() {
        let toml_str = r#"
name = "git"
description = "Fast, scalable, distributed revision control system"
aliases = ["g"]

[[options]]
names = ["--version", "-v"]
description = "Prints the Git suite version"

[[subcommands]]
name = "checkout"
aliases = ["co"]
description = "Switch branches or restore working tree files"

[[subcommands.options]]
names = ["-b"]
description = "Create and checkout a new branch"

[[subcommands.args]]
name = "branch"
generators = ["git_branches"]
"#;

        let spec = parse_spec_toml(toml_str).expect("parse toml");
        assert_eq!(spec.name, "git");
        assert_eq!(spec.aliases, vec!["g"]);
        assert_eq!(spec.options.len(), 1);
        assert_eq!(spec.subcommands.len(), 1);
        assert_eq!(spec.subcommands[0].name, "checkout");

        let generated = compile_specs_to_rust(&[spec]);
        assert!(generated.contains("pub static COMPILED_SPECS: &[StaticCommandSpec]"));
        assert!(generated.contains("name: \"git\""));
        assert!(generated.contains("name: \"checkout\""));
    }
}
